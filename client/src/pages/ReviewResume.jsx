import { FileText, Sparkles } from 'lucide-react';
import React, { useState } from 'react';
import axios from 'axios';
import { useAuth } from '@clerk/react';
import toast from 'react-hot-toast';
import Markdown from 'react-markdown';

axios.defaults.baseURL = import.meta.env.VITE_BASE_URL;

const ReviewResume = () => {
    
    const [file, setFile] = useState(null);
    const [loading, setLoading] = useState(false);
    const [content, setContent] = useState('');

    const { getToken } = useAuth();

    const onSubmitHandler = async (e) => {
        e.preventDefault();
        
        // Manual validation replaces HTML5 'required' for the file input
        if (!file) {
            toast.error("Please upload a resume first");
            return;
        }

        try {
            setLoading(true);
            
            // Use FormData to package the file for Multer
            const formData = new FormData();
            // The key 'resume' matches your backend route: upload.single('resume')
            formData.append('resume', file); 

            const token = await getToken();
            
            // Call your backend resumeReview controller
            const { data } = await axios.post('/api/ai/resume-review', 
                formData,
                { 
                    headers: { 
                        Authorization: `Bearer ${token}`,
                        'Content-Type': 'multipart/form-data'
                    }
                } 
            );
        
            if (data.success) {
                // The backend returns the text response generated by the AI
                setContent(data.content);
                toast.success('Resume reviewed successfully!');
            } else {
                toast.error(data.message); 
            }
        } catch (error) {
            console.error("🚨 [FRONTEND] API Error:", error);
            toast.error(error.response?.data?.message || error.message);
        } finally {
            setLoading(false); 
        }
    };

    return (
        <div className='h-full overflow-y-scroll p-6 flex items-start flex-wrap gap-4 text-slate-700'>
            
            {/* Left Col */}
            <form onSubmit={onSubmitHandler} className='w-full max-w-lg p-6 bg-white rounded-lg border border-gray-200'>
                <div className='flex items-center gap-3'>
                    <Sparkles className='w-6 text-[#00B47D]' />
                    <h1 className='text-xl font-semibold'>Resume Review</h1>
                </div>

                <p className='mt-6 text-sm font-medium'>Upload Resume</p>
                <input 
                    onChange={(e) => setFile(e.target.files[0])} 
                    type="file" 
                    accept='.pdf, image/*' 
                    className='w-full p-2 px-3 mt-2 outline-none text-sm rounded-md border border-gray-300 text-gray-600 cursor-pointer'
                    /* REMOVED: 'required' to prevent native browser blocking */
                />
                <p className='text-xs text-gray-500 font-light mt-1'>Supports PDF, PNG, JPG formats</p>

                {/* ADDED: type="submit" and loading spinner logic */}
                <button type="submit" disabled={loading} className='w-full flex justify-center items-center gap-2 bg-gradient-to-r from-[#00B47D] to-[#008E9B] text-white px-4 py-3 mt-8 text-sm font-medium rounded-lg cursor-pointer hover:opacity-90 transition disabled:opacity-75 disabled:cursor-not-allowed'>
                    {loading ? (
                        <span className='w-5 h-5 border-2 border-white border-t-transparent rounded-full animate-spin'></span>
                    ) : (
                        <FileText className='w-5 h-5' />
                    )}
                    Review Resume
                </button>
            </form>

            {/* Right Col */}
            <div className='flex-1 min-w-[300px] p-6 bg-white rounded-lg flex flex-col border border-gray-200 min-h-96 max-h-[600px]'>
                <div className='flex items-center gap-3 pb-4 border-b border-gray-100'>
                    <FileText className='w-6 text-[#00B47D]' />
                    <h1 className='text-xl font-semibold'>Analysis Results</h1>
                </div>

                {!content ? (
                    <div className='flex-1 flex justify-center items-center'>
                        <div className='text-sm flex flex-col items-center gap-5 text-gray-400'>
                            <FileText className='w-16 h-16 opacity-50' />
                            <p className='text-sm max-w-xs text-center leading-relaxed'>Upload your resume and click "Review Resume" to get started</p>
                        </div>
                    </div>
                ) : (
                    <div className='mt-3 h-full overflow-y-scroll text-sm text-slate-600'>
                        <div className='reset-tw'>
                            {/* Rendering the AI text analysis via Markdown */}
                            <Markdown>{content}</Markdown>
                        </div>
                    </div>
                )}
            </div>

        </div>
    );
};

export default ReviewResume;